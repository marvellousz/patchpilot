"""Renders the Bug Proof Pack (PR body) and the escalation comment."""

from patchpilot.agent import Outcome
from patchpilot.memory import RunMemory
from patchpilot.verifier import Verifier, pytest_summary


def _tail(text: str, lines: int = 25) -> str:
    return "\n".join(text.strip().splitlines()[-lines:])


def _quote(text: str, lines: int = 8) -> str:
    # Stop before the first code block so a cut-off fence can't break the rest of the PR body.
    kept = []
    for line in (text or "").strip().splitlines()[:lines]:
        if line.lstrip().startswith("```"):
            break
        kept.append(f"> {line}")
    return "\n".join(kept)


def _hypotheses(memory: RunMemory) -> str:
    items = memory.of_kind("hypothesis")
    if not items:
        return "_none recorded_"
    return "\n".join(f"- {h['hypothesis']}" + (f" (evidence: {h['evidence']})" if h.get("evidence") else "")
                     for h in items)


def render_proof_pack(issue: dict, outcome: Outcome, verifier: Verifier, memory: RunMemory,
                      diff: str, model: str, steps: int) -> str:
    added = sum(a for a, _ in verifier.source_stats.values())
    removed = sum(r for _, r in verifier.source_stats.values())
    files = ", ".join(f"`{f}`" for f in verifier.source_stats)
    return f"""## Bug Proof Pack

Fixes #{issue['number']}

### 1. Symptom
**{issue['title']}** ([#{issue['number']}]({issue.get('html_url', '')}))
{_quote(issue.get('body', ''))}

### 2. Reproduction
`{verifier.repro_file}` fails on the original code:
```text
{_tail(verifier.repro_before.output)}
```

### 3. Diagnosis
{outcome.root_cause}

<details><summary>Hypotheses considered</summary>

{_hypotheses(memory)}
</details>

### 4. Repair
{outcome.summary}

Changed {files} (+{added} -{removed}) and added regression test `{verifier.repro_file}`.

<details><summary>Diff</summary>

```diff
{diff.strip()}
```
</details>

### 5. Verification
| Check | Result |
|---|---|
| Reproduction test fails before the fix | ✅ {pytest_summary(verifier.repro_before.output)} |
| Failure matches the reported symptom | ✅ {verifier.symptom_reason} |
| Reproduction test passes after the fix | ✅ {pytest_summary(verifier.repro_after.output)} |
| Full test suite | ✅ {pytest_summary(verifier.suite_after.output)} |
| Diff scope | ✅ {len(verifier.source_stats)} source file(s), {added + removed} lines |

---
_Generated by PatchPilot AI ({model}, {steps} steps). A human must review and approve this change before merge._
"""


def render_escalation(issue: dict, outcome: Outcome, verifier: Verifier, memory: RunMemory) -> str:
    repro = (f"Reproduced with `{verifier.repro_file}`." if verifier.repro_file
             else "Could not reproduce the failure.")
    return f"""### PatchPilot needs a human

{outcome.reason}

**Reproduction:** {repro}

**Hypotheses considered:**
{_hypotheses(memory)}

_PatchPilot stopped instead of guessing. No changes were pushed._
"""
